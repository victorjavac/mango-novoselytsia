const catalog = [];

for (const [id, meta] of Object.entries(categoriesMeta)) {
    const dirPath = path.join(__dirname, id);
    let items = [];

    if (fs.existsSync(dirPath)) {
        const files = fs.readdirSync(dirPath).filter(file => file.endsWith('.webp') || file.endsWith('.jpg') || file.endsWith('.png'));
        files.sort((a, b) => parseInt(a) - parseInt(b));

        const knownTitles = photoTitles[id] || {};
        const fallbackPool = fallbackTitlePools[id] || fallbackTitlePools.default;
        let fallbackIndex = 0;

        files.forEach((file) => {
            const title = knownTitles[file] || fallbackPool[fallbackIndex++ % fallbackPool.length];
            items.push({
                src: `${id}/${file}`,
                title
            });
        });
    }

    if (items.length > 0) {
        catalog.push({
            id: id,
            title: meta.title,
            cover: items[0].src,
            count: items.length,
            alt: meta.alt,
            text: meta.text,
            items: items
        });
    }
}

fs.writeFileSync(path.join(__dirname, 'products.json'), JSON.stringify(catalog, null, 2), 'utf8');

